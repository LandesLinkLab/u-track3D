%% ---- Helper functions ----
    function writeHeading(sel, text, level)
        sel.Style = ['Heading ' num2str(level)];
        sel.Font.Name = 'Times New Roman';
        sel.Font.Bold = true;
        sel.Font.Italic = false;
        sel.Font.set('Color', 0); % black
        if level == 1
            sel.Font.Size = 14;
        elseif level == 2
            sel.Font.Size = 12;
        end
        sel.TypeText(text);
        sel.TypeParagraph;
    end

    function writeBody(sel, text)
        sel.Style = 'Normal';
        sel.Font.Name = 'Times New Roman';
        sel.Font.Size = 11;
        sel.Font.Bold = false;
        sel.Font.Italic = false;
        sel.Font.set('Color', 0); % black
        sel.ParagraphFormat.Alignment = 0; % wdAlignParagraphLeft
        sel.ParagraphFormat.SpaceAfter = 6;
        sel.ParagraphFormat.LineSpacingRule = 5; % wdLineSpaceMultiple
        sel.ParagraphFormat.LineSpacing = 14.4; % ~1.15 spacing
        sel.TypeText(text);
        sel.TypeParagraph;
    end

    function writeBodyAuto(sel, wordDoc, txt)
        % Body paragraph with inline math. Wrap math segments in $...$.
        % Each $...$ becomes an inline OMath equation field.
        sel.Style = 'Normal';
        sel.ParagraphFormat.Alignment = 0;
        sel.ParagraphFormat.SpaceAfter = 6;
        sel.ParagraphFormat.LineSpacingRule = 5;
        sel.ParagraphFormat.LineSpacing = 14.4;
        parts = regexp(txt, '\$([^\$]*)\$', 'split');
        maths = regexp(txt, '\$([^\$]*)\$', 'tokens');
        for kk = 1:length(parts)
            sel.Font.Name = 'Times New Roman';
            sel.Font.Size = 11;
            sel.Font.Italic = false;
            sel.Font.Bold = false;
            sel.Font.set('Color', 0);
            if ~isempty(parts{kk})
                sel.TypeText(parts{kk});
            end
            if kk <= length(maths)
                mtxt = maths{kk}{1};
                sel.Font.Name = 'Cambria Math';
                sel.Font.Italic = true;
                sel.Font.set('Color', 0);
                startPos = sel.Range.Start;
                sel.TypeText(mtxt);
                endPos = sel.Range.Start;
                try
                    eqRange = wordDoc.Range(startPos, endPos);
                    om = wordDoc.OMaths.Add(eqRange);
                    om.Type = 1; % wdOMathInline
                catch ME
                    fprintf('  Inline math warning: %s\n', ME.message);
                end
                sel.EndKey(6); % wdStory
            end
        end
        sel.TypeParagraph;
    end

    function writeEquation(sel, wordDoc, eqText)
        % Insert equation using Word's OMML via COM.
        % eqText should be in Word's Unicode linear math format.
        sel.Style = 'Normal';
        sel.ParagraphFormat.Alignment = 1; % wdAlignParagraphCenter
        sel.ParagraphFormat.SpaceAfter = 2;
        sel.ParagraphFormat.SpaceBefore = 6;
        sel.Font.Name = 'Cambria Math';
        sel.Font.Size = 11;
        sel.Font.Italic = true;
        sel.Font.set('Color', 0); % black
        startPos = sel.Range.Start;
        sel.TypeText(eqText);
        endPos = sel.Range.Start;
        try
            eqRange = wordDoc.Range(startPos, endPos);
            omath = wordDoc.OMaths.Add(eqRange);
        catch ME
            fprintf('  Equation warning (Add): %s\n', ME.message);
        end
        sel.EndKey(6); % wdStory
        sel.TypeParagraph;
    end

    function writeCodeRef(sel, refText)
        % Write a code location reference in small gray italic text
        % Word COM Color uses BGR format: R + G*256 + B*256^2
        sel.Style = 'Normal';
        sel.ParagraphFormat.Alignment = 1; % wdAlignParagraphCenter
        sel.ParagraphFormat.SpaceAfter = 6;
        sel.ParagraphFormat.SpaceBefore = 0;
        sel.Font.Name = 'Consolas';
        sel.Font.Size = 8;
        sel.Font.Italic = true;
        sel.Font.Bold = false;
        sel.Font.set('Color', 128 + 128*256 + 128*65536); % Gray (RGB 128,128,128)
        sel.TypeText(['Code: ' refText]);
        sel.TypeParagraph;
        % Reset font color to black
        sel.Font.set('Color', 0); % Black
    end

    function writeRef(sel, num, text)
        % Write a numbered reference entry
        sel.Style = 'Normal';
        sel.Font.Name = 'Times New Roman';
        sel.Font.Size = 10;
        sel.Font.Bold = false;
        sel.Font.Italic = false;
        sel.ParagraphFormat.Alignment = 0;
        sel.ParagraphFormat.SpaceAfter = 4;
        sel.ParagraphFormat.LeftIndent = 28; % hanging indent
        sel.ParagraphFormat.FirstLineIndent = -28;
        sel.Font.set('Color', 0);
        sel.TypeText(['[' num2str(num) '] ' text]);
        sel.TypeParagraph;
        sel.ParagraphFormat.LeftIndent = 0;
        sel.ParagraphFormat.FirstLineIndent = 0;
    end


%% ---- 2. SPATIAL KALMAN FILTER ----
writeHeading(sel, '2. Spatial Tracking via Kalman Filtering', 1);

rh = ['r' hat];

writeBodyAuto(sel, wdoc, ...
    ['The u-track3D Kalman filter provides optimal position predictions by recursively estimating particle state vectors from noisy localizations [2]. ' ...
    'For each tracked particle, the state vector $' rh '$ contains position and velocity components in each spatial dimension. ' ...
    'For example, in three dimensions $' rh '=(x, v_x, y, v_y, z, v_z)$, ' ...
    'where $x$, $y$, $z$ are the spatial coordinates and $v_x$, $v_y$, $v_z$ are the corresponding velocities. ' ...
    'The notation $' rh '(t|t-1)$ reads "the estimate of $' rh '$ at frame $t$, given all observations through frame $t-1$"; ' ...
    'the vertical bar means "given" and separates the time being estimated from the last time data was available.']);

writeBodyAuto(sel, wdoc, ...
    ['At each frame transition, the filter predicts where the particle will be in the next frame ' ...
    'by propagating the current state estimate forward through a linear motion model. ' ...
    'The state prediction equation is:']);

writeEquation(sel, wdoc, [rh '(t|t-1)=F' cdot rh '(t-1|t-1)']);
writeCodeRef(sel, 'costMatRandomDirectedSwitchingMotionLink.m:217');

writeBodyAuto(sel, wdoc, ...
    ['This equation multiplies the previous state estimate $' rh '(t-1|t-1)$ by the state transition matrix $F$ ' ...
    'to obtain a predicted state $' rh '(t|t-1)$ for the current frame. ' ...
    'The matrix $F$ encodes the assumed motion model; for constant-velocity motion, ' ...
    '$F$ propagates positions forward by adding velocity times the frame interval. ' ...
    'The variable $t$ denotes the current frame index and $t-1$ the previous frame.']);

writeBodyAuto(sel, wdoc, ...
    ['Along with the state prediction, the filter must also predict how its uncertainty grows over time. ' ...
    'The state covariance matrix $P$ quantifies the uncertainty in the state estimate: ' ...
    'larger values of $P$ indicate less confidence in the predicted position. ' ...
    'The covariance prediction equation is:']);

writeEquation(sel, wdoc, ['P(t|t-1)=F' cdot 'P(t-1|t-1)' cdot 'F^T+Q']);
writeCodeRef(sel, 'costMatRandomDirectedSwitchingMotionLink.m:220-221');

writeBodyAuto(sel, wdoc, ...
    ['This equation propagates the previous covariance $P(t-1|t-1)$ through the motion model $F$, ' ...
    'then adds the process noise covariance $Q$. ' ...
    'The superscript $T$ denotes the matrix transpose. ' ...
    'The transpose appears because covariance matrices transform as $F' cdot 'P' cdot 'F^T$ under a linear operation $F$, ' ...
    'a standard result from linear algebra [2]. ' ...
    'The matrix $Q$ represents the random component of particle motion between frames: ' ...
    'even a perfect position estimate becomes less certain after one frame because the particle moves stochastically.']);

writeBodyAuto(sel, wdoc, ...
    ['u-track3D evaluates multiple competing motion models (e.g., Brownian, directed, switching), ' ...
    'each with its own transition matrix $F$. ' ...
    'The prediction step is performed under each model, and the model yielding the lowest cost ' ...
    'for a given track-detection pair is selected [1].']);

writeHeading(sel, '2.1 Innovation and Kalman Gain', 2);

writeBodyAuto(sel, wdoc, ...
    ['After predicting the state, the filter compares the prediction to the actual measurement. ' ...
    'The innovation (or residual) $y$ is the difference between the observed detection position $m$ ' ...
    'and the predicted observation. We use the symbol $m$ (for "measurement") rather than $z$, ' ...
    'because $z$ is already reserved for the axial spatial coordinate of the dipole.']);

writeEquation(sel, wdoc, ['y=m-H' cdot rh '(t|t-1)']);
writeCodeRef(sel, 'kalmanGainLinearMotion.m:158');

writeBodyAuto(sel, wdoc, ...
    ['Here $m$ is the measured position vector of the candidate detection, ' ...
    'and $H$ is the observation matrix that extracts the position components from the full state vector ' ...
    '(since $' rh '$ contains both positions and velocities, but $m$ contains only positions). ' ...
    'The product $H' cdot rh '(t|t-1)$ gives the predicted position in measurement space.']);

writeBodyAuto(sel, wdoc, ...
    ['The innovation covariance $S$ quantifies the total uncertainty in the innovation, ' ...
    'combining the prediction uncertainty with the measurement noise:']);

writeEquation(sel, wdoc, ['S=H' cdot 'P(t|t-1)' cdot 'H^T+R']);
writeCodeRef(sel, 'kalmanGainLinearMotion.m:149-151');

writeBodyAuto(sel, wdoc, ...
    ['The matrix $R$ is the measurement noise covariance, constructed from the squared localization uncertainties ' ...
    'reported for each detection. ' ...
    'The Kalman gain $K$, which determines how much the filter trusts the new measurement versus its prediction, is:']);

writeEquation(sel, wdoc, ['K=P(t|t-1)' cdot 'H^T' cdot 'S^(-1)']);
writeCodeRef(sel, 'kalmanGainLinearMotion.m:149-151');

writeBodyAuto(sel, wdoc, ...
    ['The Kalman gain $K$ weights the innovation $y$ to produce a correction $K' cdot 'y$ ' ...
    'that is applied to the predicted state. ' ...
    'When the prediction uncertainty $P$ is large relative to the measurement noise $R$, ' ...
    'the gain is large and the filter trusts the measurement. ' ...
    'When $P$ is small relative to $R$, the gain is small and the filter trusts its prediction.']);

writeHeading(sel, '2.2 Spatial Linking Cost', 2);

writeBody(sel, ...
    ['The spatial linking cost between a predicted track position and a candidate detection ' ...
    'is the squared Euclidean distance between the predicted observation and the measured position [1]:']);

writeEquation(sel, wdoc, ['C_(spatial)(i,j)=||m_j-H' cdot rh '_i(t|t-1)||^2']);
writeCodeRef(sel, 'costMatRandomDirectedSwitchingMotionLink.m:249,301');

writeBodyAuto(sel, wdoc, ...
    ['Here $i$ indexes the track and $j$ indexes the candidate detection. ' ...
    'The cost is computed for each combination of motion model (propagation scheme), ' ...
    'and the minimum cost across all models is retained. ' ...
    'This is a Euclidean distance squared, not normalized by the innovation covariance $S$.']);

writeBodyAuto(sel, wdoc, ...
    ['The Kalman filter''s uncertainty enters the cost matrix indirectly through a search radius gate. ' ...
    'For each track, the search radius is proportional to the Kalman standard deviation ' ...
    '$' sqrt_ch '(P)$, multiplied by a user-specified factor (brownStdMult, default: 3). ' ...
    'The search radius may be expanded based on local particle density, ' ...
    'but is clamped between user-specified minimum and maximum values. ' ...
    'Track-detection pairs whose distance exceeds the search radius are excluded from the cost matrix ' ...
    'by setting their cost to infinity (nonlinkMarker) [1]. ' ...
    'The remaining valid entries are then solved by the Jonker-Volgenant algorithm [7] ' ...
    'to obtain the globally optimal frame-to-frame assignment.']);

%% ---- 3. ORIENTATION COST: LEVEL 3 ----
writeHeading(sel, '3. Orientation Cost Function: Adaptive Three-Model Kalman (Level 3)', 1);

writeHeading(sel, '3.1 Angular Distance with Dipole Symmetry', 2);

writeBodyAuto(sel, wdoc, ...
    ['The angular distance between two dipole orientations must respect the head-tail symmetry inherent to fluorescent dipole emitters [3,4]. ' ...
    'A fluorescent dipole oriented at angles $(' theta ', ' phi_ch ')$ is physically indistinguishable from one at ' ...
    '$(' pi_ch '-' theta ', ' phi_ch '+' pi_ch ')$, ' ...
    'producing identical emission patterns in single-molecule imaging. ' ...
    'To enforce this symmetry, we convert the spherical angles to unit vectors on the upper hemisphere ' ...
    'and define the angular distance through the absolute value of their dot product:']);

muh = [mu_ch hat];
kh = ['k' hat];
writeEquation(sel, wdoc, [muh '=(sin' theta ' cos' phi_ch ',  sin' theta ' sin' phi_ch ',  cos' theta ')']);
writeCodeRef(sel, 'costMat6DSMOLMLink.m:611  |  generate6DTrajectories.m:367-368');

writeEquation(sel, wdoc, [psi_ch '=arccos(|' muh '_1' cdot muh '_2|)']);
writeCodeRef(sel, 'costMat6DSMOLMLink.m:624-625  (computeAngularDistanceMatrix)');

writeBodyAuto(sel, wdoc, ...
    ['The resulting angular distance $' psi_ch '$ lies in the range $[0, ' pi_ch '/2]$, correctly identifying antipodal orientations as identical. ' ...
    'This is the fundamental distance metric used throughout the orientation cost computation.']);

writeHeading(sel, ['3.2 Rotational Brownian Dynamics on S' sup2], 2);

writeBodyAuto(sel, wdoc, ...
    ['The expected angular displacement of a freely rotating dipole follows from rotational Brownian dynamics on the unit sphere $S^2$ [5]. ' ...
    'On $S^2$, the orientation diffuses along two independent tangent-plane directions, ' ...
    'each contributing a variance of $2D_(rot) ' delta_ch 't$ per time step, where $D_(rot)$ is the rotational diffusion coefficient. ' ...
    'The total mean-squared angular displacement therefore involves two components:']);

writeEquation(sel, wdoc, ['E[' delta_ch psi_ch sup2 ']=4D_(rot) ' delta_ch 't']);
writeCodeRef(sel, 'costMat6DSMOLMLink.m:426,429  |  generate6DTrajectories.m:619,632');

writeBodyAuto(sel, wdoc, ...
    ['This factor of 4 (rather than 2) distinguishes rotational diffusion on $S^2$ from one-dimensional translational diffusion [5]. ' ...
    'It is the rotational analog of the well-known result that mean-squared displacement in $d$ dimensions equals $2dDt$. ' ...
    'In the trajectory generator, two independent Gaussian samples with $' sigma_ch '=' sqrt_ch '(2D_(rot)' delta_ch 't)$ are drawn ' ...
    'in the tangent plane at the current orientation, producing a net angular step whose squared magnitude has expectation $4D_(rot)' delta_ch 't$.']);

writeHeading(sel, '3.3 Three Competing Motion Models', 2);

writeBodyAuto(sel, wdoc, ...
    ['Level 3 orientation tracking evaluates three competing propagation schemes for each track-detection candidate pair $(i, j)$ ' ...
    'and selects the scheme yielding the lowest cost. ' ...
    'These three schemes are the rotational analog of the forward / backward / Brownian translational motion models in ' ...
    'u-track3D''s costMatRandomDirectedSwitchingMotionLink, which evaluates linear motion in three directions (forward along the velocity, ' ...
    'backward along the velocity, and pure Brownian) and likewise picks the minimum-cost scheme [1]. ' ...
    'Here, instead of translating positions by $' char(177) 'v' delta_ch 't$ or leaving them in place, we rotate the dipole orientation ' ...
    'by $' char(177) '|' char(969) '|' delta_ch 't$ about the learned angular-velocity axis, or leave it unchanged.']);

writeBodyAuto(sel, wdoc, ...
    ['Let $' muh '_i$ denote the current orientation of track $i$, and let $' char(969) '_i$ be its estimated angular-velocity vector ' ...
    '(extracted from the last two frames of track history via the Rodrigues axis-angle that rotates $' muh '_i(t-1)$ into $' muh '_i(t)$). ' ...
    'Define $' kh '_i=' char(969) '_i / |' char(969) '_i|$. The three predicted orientations for the next frame are:']);

writeEquation(sel, wdoc, [muh '_(fwd)=Rodrigues(' muh '_i, ' kh '_i, +|' char(969) '_i|)']);
writeCodeRef(sel, 'costMat6DSMOLMLink.m:448');

writeEquation(sel, wdoc, [muh '_(bwd)=Rodrigues(' muh '_i, ' kh '_i, -|' char(969) '_i|)']);
writeCodeRef(sel, 'costMat6DSMOLMLink.m:449');

writeEquation(sel, wdoc, [muh '_(brn)=' muh '_i']);
writeCodeRef(sel, 'costMat6DSMOLMLink.m:455');

writeBodyAuto(sel, wdoc, ...
    ['The forward scheme assumes the dipole continues tumbling in the same sense as in the previous interval; ' ...
    'the backward scheme assumes it reverses; the Brownian scheme assumes any apparent rotation is purely diffusive ' ...
    '(no preferred axis). All three schemes share the same predicted angular variance $S_' psi_ch '$ ' ...
    '(defined in Section 3.5 below): only the predicted mean $' muh '$ differs.']);

writeBody(sel, ...
    'Orientation propagation uses the Rodrigues rotation formula with the sign convention of Hofling and Straube [5]:');

writeEquation(sel, wdoc, [muh '_(rot)=' muh ' cos' alpha_ch '-(' kh cross_ch muh ')sin' alpha_ch '+' kh '(' kh cdot muh ')(1-cos' alpha_ch ')']);
writeCodeRef(sel, 'costMat6DSMOLMLink.m:738-740  (rotateVector)  |  generate6DTrajectories.m:700-702  (rodrigues_rotate)');

writeBodyAuto(sel, wdoc, ...
    ['Here $' kh '$ is the unit rotation axis and $' alpha_ch '$ is the rotation angle. ' ...
    'The negative sign on the cross-product term follows the convention used in the synthetic trajectory generator (generate6DTrajectories.m), ' ...
    'ensuring consistency between simulation and tracking. ' ...
    'The angular velocity is estimated from the last two frames of track history by computing the Rodrigues axis and angle ' ...
    'that rotate the previous orientation into the current one.']);

writeHeading(sel, '3.4 Per-Track D_(rot) Learning', 2);

writeBodyAuto(sel, wdoc, ...
    ['The rotational diffusion coefficient $D_(rot)$ is learned adaptively for each track from its angular displacement history. ' ...
    'This is the rotational analog of the noise-corrected mean-squared displacement (MSD) estimator routinely used to extract ' ...
    'translational diffusion coefficients from camera-based single-particle tracks [6,11]. ' ...
    'The derivation proceeds in three steps.']);

writeBodyAuto(sel, wdoc, ...
    ['Step 1: Decompose the observed angular step. For each consecutive pair of detections in a track, ' ...
    'the measured angular displacement $' delta_ch alpha_ch '$ between the two noisy dipole orientations decomposes into the true rotational step ' ...
    'plus two independent measurement-noise contributions $' char(949) '_t$ and $' char(949) '_(t+' delta_ch 't)$, one at each endpoint:']);

writeEquation(sel, wdoc, [delta_ch alpha_ch '_(obs)=' delta_ch alpha_ch '_(true)+' char(949) '_(t+' delta_ch 't)-' char(949) '_t']);

writeBodyAuto(sel, wdoc, ...
    ['Each per-detection angular noise $' char(949) '$ has variance $' sigma_ch '_' psi_ch '^2$, the orientational Cramer-Rao lower bound [4]. ' ...
    'Because the true step and the two noises are uncorrelated, variances add:']);

writeEquation(sel, wdoc, [langle delta_ch alpha_ch sup2 rangle '_(obs)=' langle delta_ch alpha_ch sup2 rangle '_(true)+2' sigma_ch '_' psi_ch sup2]);

writeBodyAuto(sel, wdoc, ...
    ['The factor of 2 reflects the fact that two independent noisy orientation measurements (one at each end of the step) ' ...
    'each contribute $' sigma_ch '_' psi_ch '^2$.']);

writeBodyAuto(sel, wdoc, ...
    ['Step 2: Substitute the rotational Brownian dynamics result. ' ...
    'From Section 3.2 (and the tangent-plane construction visualized in the Appendix), ' ...
    'the true mean-squared angular displacement on the unit sphere is:']);

writeEquation(sel, wdoc, [langle delta_ch alpha_ch sup2 rangle '_(true)=4D_(rot)' delta_ch 't']);

writeBodyAuto(sel, wdoc, ...
    'Combining with the previous equation gives:');

writeEquation(sel, wdoc, [langle delta_ch alpha_ch sup2 rangle '_(obs)=4D_(rot)' delta_ch 't+2' sigma_ch '_' psi_ch sup2]);

writeBodyAuto(sel, wdoc, ...
    'Step 3: Solve for $D_(rot)$. Rearranging gives the noise-corrected MSD estimator used in the code:');

writeEquation(sel, wdoc, ['D_(rot)=(' langle delta_ch alpha_ch sup2 rangle '-2' sigma_ch '_' psi_ch sup2 ')/(4' delta_ch 't)']);
writeCodeRef(sel, 'costMat6DSMOLMLink.m:322-323');

writeBodyAuto(sel, wdoc, ...
    ['This is structurally identical to the translational MSD estimator $D=(' langle delta_ch 'r^2' rangle '-2' sigma_ch '_(xy)^2)/(2d' delta_ch 't)$, ' ...
    'derived in Michalet (2010) for single-particle tracking with localization error [11], ' ...

sumSym = char(8721); % ∑
writeEquation(sel, wdoc, ['A' hat '=arg min ' sumSym '_(i=1)^(N_(rows)) ' sumSym '_(j=1)^(N_(cols)) A_(i,j)' cdot 'C(i,j)']);
writeCodeRef(sel, 'lap.m  (Jonker-Volgenant solver, called from u-track3D)');

writeBodyAuto(sel, wdoc, ...
    'subject to the one-to-one assignment constraints:');

writeEquation(sel, wdoc, [sumSym '_(i=1)^(N_(rows)) A_(i,j)=1,    ' sumSym '_(j=1)^(N_(cols)) A_(i,j)=1']);

writeBodyAuto(sel, wdoc, ...
    ['These constraints enforce that each row (track) is matched to exactly one column (detection), and vice versa. ' ...
    'Birth and death dummy entries in the augmented cost matrix allow tracks to start, end, or skip frames. ' ...
    'This $' sumSym sumSym '$ formulation is identical in structure to Eqs. (1)-(2) of Jaqaman et al. [1] ' ...
    'and is solved by the Jonker-Volgenant algorithm [7].']);

writeBodyAuto(sel, wdoc, ...
    ['The weight $w_(spatial)$ (default 1.0) scales the spatial cost, ' ...
    '$w_(orient)$ (default 1.0) scales the orientation cost, ' ...
    'and $w_' omega_ch '$ (default 0.0) scales an optional wobble continuity cost. ' ...
    'The wobble cost $C_' omega_ch '$ penalizes changes in the wobble solid angle $' omega_ch '$ between linked detections. ' ...
    'Only the upper-left block of the cost matrix (valid linking region) receives the orientation augmentation; ' ...
    'the birth, death, and auxiliary blocks remain unmodified from the base u-track3D output [1].']);

writeBodyAuto(sel, wdoc, ...
    ['The augmented cost matrix is solved by the Jonker-Volgenant algorithm [7] to obtain the globally optimal assignment. ' ...
    'This algorithm solves the linear assignment problem in $O(n^3)$ time, ' ...
    'simultaneously minimizing the total spatial and orientational linking cost across all particles, ' ...
    'subject to the constraint that each detection is assigned to at most one track [1]. ' ...
    'Unmatched tracks are terminated (assigned to death dummies) and unmatched detections initiate new tracks (birth dummies). ' ...
    'The key advantage of the additive cost formulation is that orientation information naturally resolves spatial ambiguities: ' ...
    'when two tracks approach the same detection, the orientation cost breaks the tie in favor of the track ' ...
    'with compatible angular coordinates (Figure 2A).']);

writeHeading(sel, '4.1 Gap Closing with Orientation', 2);

writeBodyAuto(sel, wdoc, ...
    ['The second LAP closes gaps between track segments using orientation similarity as additional evidence for segment identity [1]. ' ...
    'When a track segment ends at frame $t_(end)$ and another begins at frame $t_(start)$ (with $t_(start)>t_(end)+1$), ' ...
    'the gap-closing cost combines spatial proximity with angular distance between the endpoint and startpoint orientations. ' ...
    'The angular distance is normalized by the square root of the time gap to account for expected rotational diffusion during the gap interval, ' ...
    'since the mean angular displacement scales as $' sqrt_ch '(4D_(rot)' delta_ch 't)$ under Brownian rotation [5]. ' ...
    'Three scenarios illustrate the value of orientation in gap closing (Figure 2B): ' ...
    '(i) a track gap is correctly closed when the endpoint and startpoint share compatible orientations; ' ...
    '(ii) a gap closure is rejected when orientations mismatch despite spatial proximity; ' ...
    'and (iii) crossing tracks that are spatially ambiguous are correctly resolved by their distinct orientation signatures. ' ...
    'Merge and split events are not currently used in the 6D-SMOLM implementation (mergeSplit = 0), ' ...
    'as individual fluorescent molecules do not undergo aggregation or disaggregation [1].']);

